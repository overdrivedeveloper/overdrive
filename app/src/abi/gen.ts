// Pure generator: turns the IOD*.json ABIs (written by .github/scripts/export-abis.sh from the forge build) into typed `as const` modules.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export const HEADER = "// GENERATED by scripts/gen-abi-ts.ts from the IOD*.json ABIs. Do not edit; run `bun run scripts/gen-abi-ts.ts`.\n";

export function interfaceNames(jsonDir: string): string[] {
  return readdirSync(jsonDir)
    .filter((file) => /^IOD[A-Za-z0-9]+\.json$/.test(file))
    .map((file) => file.replace(/\.json$/, ""))
    .sort();
}

/** file name (relative to the abi dir) to content, for every interface plus index.ts. */
export function generateAll(jsonDir: string): Map<string, string> {
  const out = new Map<string, string>();
  const names = interfaceNames(jsonDir);
  for (const name of names) {
    const abi = JSON.parse(readFileSync(join(jsonDir, `${name}.json`), "utf8")) as unknown;
    out.set(`${name}.ts`, `${HEADER}export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
  }
  const lines = [HEADER.trimEnd(), ""];
  for (const name of names) lines.push(`import { ${name}Abi } from "./${name}";`);
  lines.push("");
  for (const name of names) lines.push(`export { ${name}Abi };`, `export const ${name} = ${name}Abi;`);
  lines.push("", "/** Every interface ABI by its IOD* name. */", "export const ABIS = {");
  for (const name of names) lines.push(`  ${name}: ${name}Abi,`);
  lines.push("} as const;", "");
  out.set("index.ts", lines.join("\n"));
  return out;
}

/** Names of generated files that differ from `abiDir` (missing, changed, or stale extra IOD*.ts files). */
export function drift(jsonDir: string, abiDir: string): string[] {
  const want = generateAll(jsonDir);
  const bad: string[] = [];
  for (const [file, content] of want) {
    let have: string | undefined;
    try { have = readFileSync(join(abiDir, file), "utf8"); } catch { have = undefined; }
    if (have !== content) bad.push(file);
  }
  for (const file of readdirSync(abiDir)) {
    if (/^IOD[A-Za-z0-9]+\.ts$/.test(file) && !want.has(file)) bad.push(file);
  }
  return bad.sort();
}
