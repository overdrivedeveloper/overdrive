// Writes src/mcp/pinned.generated.ts from deployments/<chain>.json (default mainnet). With no file the pin is empty.
// `--check` fails when the committed file differs. Usage: bun run scripts/gen-mcp-pin.ts [--check] [--file path]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseDeployment } from "../src/lib/deployments";
import { EMPTY_PIN, pinFromDeployment } from "../src/mcp/pinned";

const root = join(import.meta.dir, "..");
const fileArg = process.argv.indexOf("--file");
const source = fileArg > 0 ? process.argv[fileArg + 1]! : join(root, "deployments", "mainnet.json");
const target = join(root, "src", "mcp", "pinned.generated.ts");

export function render(pin: ReturnType<typeof pinFromDeployment>): string {
  return `// GENERATED by scripts/gen-mcp-pin.ts from deployments/mainnet.json. Do not edit. Empty until the mainnet file exists.\nimport type { PinnedDeployment } from "./pinned";\n\nexport const MAINNET_PIN: PinnedDeployment = ${JSON.stringify(pin, null, 2)};\n`;
}

if (import.meta.main) {
  const pin = existsSync(source) ? pinFromDeployment(parseDeployment(JSON.parse(readFileSync(source, "utf8")))) : EMPTY_PIN(4663);
  const text = render(pin);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== text) { console.error("pinned.generated.ts is stale: run bun run scripts/gen-mcp-pin.ts"); process.exit(1); }
  } else writeFileSync(target, text);
}
