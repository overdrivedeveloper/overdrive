#!/usr/bin/env python3
"""Audit scope list: contracts/AUDIT-SCOPE.md names every Solidity file under contracts/src.

Usage (from contracts/): python3 script/ci/audit-scope.py [--check | --write]
  --write  regenerate AUDIT-SCOPE.md from the tree
  --check  exit 1 when the file is missing or differs from what --write would produce (CI)
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "AUDIT-SCOPE.md"

KIND = {
    "interfaces": "interface or shared types",
    "math": "library (pure maths)",
}


def render() -> str:
    files = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "src").rglob("*.sol"))
    support = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "script").rglob("*.sol"))
    lines = [
        "# Audit scope",
        "",
        "Generated by `script/ci/audit-scope.py --write`; CI fails when it differs from the tree (`--check`).",
        "The audited commit is the one that carries the audit tag. Every file below is in scope at that commit;",
        "nothing under `lib/` or `test/` is. Paths are relative to `contracts/`.",
        "",
        "Compiler: solc 0.8.26 (pinned in `foundry.toml`). Chain: Robinhood Chain (4663).",
        "",
        f"## In scope: `src/` ({len(files)} files)",
        "",
        "| File | Lines | Kind |",
        "| --- | ---: | --- |",
    ]
    total = 0
    for f in files:
        n = sum(1 for _ in open(ROOT / f, encoding="utf-8"))
        total += n
        lines.append(f"| `{f}` | {n} | {KIND.get(f.split('/')[1], 'contract or library')} |")
    lines += ["", f"Total: {total} lines.", "", f"## Supporting, not in scope: `script/` ({len(support)} files)", ""]
    lines += [f"- `{f}`" for f in support]
    lines += [
        "",
        "The deploy and configuration scripts are read to confirm roles and parameters; findings in them are",
        "reported, but they hold no funds and are not deployed code.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    want = render()
    if "--write" in sys.argv:
        OUT.write_text(want, encoding="utf-8")
        print(f"audit-scope: wrote {OUT.name}")
        return 0
    have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if have != want:
        print("audit-scope: AUDIT-SCOPE.md is out of date; run python3 script/ci/audit-scope.py --write", file=sys.stderr)
        return 1
    print("audit-scope: clean")
    return 0


if __name__ == "__main__":
    sys.exit(main())
