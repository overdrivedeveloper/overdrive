#!/usr/bin/env python3
"""PRIV-2: ROLES.md, the table of every deploy role with its public holder per network, generated from
script/config/roles-published.json. --check fails when ROLES.md differs from the generated table, or when a role
in script/config/<network>.json is set (non-zero) to an address other than the published holder.
Usage: python3 script/ci/roles-table.py [--write | --check]"""
import json
import sys

ZERO = "0x" + "0" * 40
POWERS = {
    "ownerSafe": "Proposer, canceller and executor of the 48 hour timelock (DEFAULT_ADMIN_ROLE on every core through it)",
    "guardianSafe": "Guardian: pause and other risk-reducing calls only, at once",
    "keeper": "Crank key: session windows and buy and burn; no keeper power on the Governor",
    "hedger": "Hedger key on the Governor: send and return USDG, post hedge (bounded)",
    "volSigner": "Signs sigma posts for ODVolOracle (clamped, nonce, revocable by the guardian)",
    "paymasterSigner": "Signs gas sponsorship for ODPaymaster",
    "treasury": "Receives the treasury share of fees",
}


def render(pub):
    out = ["# Roles and holders", "",
           "Generated by `script/ci/roles-table.py --write` from `script/config/roles-published.json`; CI fails when this",
           "file or a deploy config (`script/config/<network>.json`) disagrees with it. Powers and bounds: `SECURITY.md`",
           "(Privileged functions). On chain, `PostDeployCheck` checks the same roles against the config.", ""]
    for net in ("testnet", "mainnet"):
        out += [f"## {net}", "", "| Role | Holder | Power |", "| --- | --- | --- |"]
        for role, power in POWERS.items():
            out.append(f"| {role} | `{pub[net][role]}` | {power} |")
        out.append("")
    return "\n".join(out)


def main(argv):
    pub = json.load(open("script/config/roles-published.json"))
    text = render(pub)
    if "--write" in argv:
        open("ROLES.md", "w").write(text)
        return 0
    bad = []
    try:
        if open("ROLES.md").read() != text:
            bad.append("ROLES.md is out of date; run python3 script/ci/roles-table.py --write")
    except FileNotFoundError:
        bad.append("ROLES.md is missing")
    for net in ("testnet", "mainnet"):
        cfg = json.load(open(f"script/config/{net}.json"))["roles"]
        for role in POWERS:
            got = cfg.get(role, ZERO)
            if got.lower() != ZERO and got.lower() != pub[net][role].lower():
                bad.append(f"{net}.json {role} = {got}, published holder is {pub[net][role]}")
        for role in cfg:
            if role not in POWERS:
                bad.append(f"{net}.json has a role {role} with no row in ROLES.md")
    for b in bad:
        print("roles-table: " + b, file=sys.stderr)
    return 1 if ("--check" in argv and bad) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
