// Generates src/generated.ts (TypeScript types for every route) from openapi.json (the file the API dumps).
// Usage: bun run scripts/generate-types.ts [--check] [openapiFile] [outFile]
// Refresh openapi.json first with `cd ../app && bun run scripts/dump-openapi.ts`. `--check` fails when generated.ts is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

type Json = Record<string, any>;

export function generate(doc: Json): string {
  const resolveRef = (ref: string): Json => {
    let node: any = doc;
    for (const part of ref.replace(/^#\//, "").split("/")) node = node?.[part];
    return node ?? {};
  };
  const literal = (value: unknown): string => JSON.stringify(value);

  function ts(schema: Json | undefined, indent: number): string {
    if (!schema || Object.keys(schema).length === 0) return "unknown";
    if (typeof schema.$ref === "string") return ts(resolveRef(schema.$ref), indent);
    if (schema.const !== undefined) return literal(schema.const);
    if (Array.isArray(schema.enum)) return schema.enum.map(literal).join(" | ");
    const variants = (schema.anyOf ?? schema.oneOf) as Json[] | undefined;
    if (variants) return variants.map((entry) => ts(entry, indent)).filter((entry, i, all) => all.indexOf(entry) === i).join(" | ");
    if (schema.allOf) return (schema.allOf as Json[]).map((entry) => `(${ts(entry, indent)})`).join(" & ");
    const types: string[] = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
    if (types.length === 0 && schema.properties) types.push("object");
    const parts = types.map((type) => {
      switch (type) {
        case "string": return "string";
        case "integer": case "number": return "number";
        case "boolean": return "boolean";
        case "null": return "null";
        case "array": return `Array<${ts(schema.items, indent)}>`;
        case "object": return object(schema, indent);
        default: return "unknown";
      }
    });
    return parts.length ? [...new Set(parts)].join(" | ") : "unknown";
  }

  function object(schema: Json, indent: number): string {
    const pad = "  ".repeat(indent + 1);
    const required = new Set<string>(schema.required ?? []);
    const props = Object.entries((schema.properties ?? {}) as Json).map(([key, value]) => {
      const note = typeof value.description === "string" ? `${pad}/** ${value.description.replace(/\*\//g, "* /").replace(/\s+/g, " ")} */\n` : "";
      return `${note}${pad}${/^[A-Za-z_$][\w$]*$/.test(key) ? key : literal(key)}${required.has(key) ? "" : "?"}: ${ts(value, indent + 1)};`;
    });
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") props.push(`${pad}[key: string]: ${ts(schema.additionalProperties, indent + 1)};`);
    else if (schema.additionalProperties === true && props.length === 0) return "Record<string, unknown>";
    return props.length ? `{\n${props.join("\n")}\n${"  ".repeat(indent)}}` : "Record<string, never>";
  }

  const out: string[] = ["// Generated by scripts/generate-types.ts from openapi.json. Do not edit by hand.", "/* eslint-disable */", "", "export interface Operations {"];
  const keys: string[] = [];
  for (const [path, item] of Object.entries(doc.paths as Json)) {
    // /v1/compat/* is the website's own contract (web/src/services); the SDK covers the public /v1 API only.
    if (path.startsWith("/v1/compat/")) continue;
    for (const method of ["get", "post", "put", "delete"]) {
      const op = item[method] as Json | undefined;
      if (!op) continue;
      const key = `${method.toUpperCase()} ${path}`;
      keys.push(key);
      const params = [...((item.parameters as Json[]) ?? []), ...((op.parameters as Json[]) ?? [])].map((entry) => (entry.$ref ? resolveRef(entry.$ref) : entry));
      const group = (where: string): string => {
        const list = params.filter((entry) => entry.in === where);
        if (list.length === 0) return "";
        const body = list.map((entry) => `${/^[A-Za-z_$][\w$]*$/.test(entry.name) ? entry.name : literal(entry.name)}${entry.required ? "" : "?"}: ${ts(entry.schema, 4)};`).join(" ");
        return `${where}: { ${body} };`;
      };
      const json = op.requestBody?.content?.["application/json"]?.schema as Json | undefined;
      const responses = Object.entries((op.responses ?? {}) as Json).map(([status, response]) => {
        const res = (response as Json).$ref ? resolveRef((response as Json).$ref) : (response as Json);
        const content = res.content as Json | undefined;
        const schema = content?.["application/json"]?.schema as Json | undefined;
        const text = content && !schema ? Object.keys(content)[0] : undefined;
        return `      ${status}: ${schema ? ts(schema, 3) : text ? "string" : "undefined"};`;
      });
      out.push(
        `  ${literal(key)}: {`,
        ...[group("path"), group("query"), json ? `body: ${ts(json, 2)};` : ""].filter(Boolean).map((line) => `    ${line}`),
        "    responses: {", ...responses, "    };", "  };",
      );
    }
  }
  out.push("}", "", `export type OperationKey = keyof Operations;`, `export const OPERATION_KEYS: readonly OperationKey[] = ${JSON.stringify(keys, null, 2)};`, "");
  return out.join("\n");
}

if (import.meta.main) {
  const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
  const input = resolve(args[0] ?? "openapi.json");
  const output = resolve(args[1] ?? "src/generated.ts");
  const text = generate(JSON.parse(readFileSync(input, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== text) { console.error("src/generated.ts is out of date: run bun run generate"); process.exit(1); }
  } else {
    writeFileSync(output, text);
    console.log(`wrote ${output}`);
  }
}
