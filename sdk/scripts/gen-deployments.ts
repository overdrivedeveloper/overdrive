// Generates src/deployments.generated.ts from app/deployments/<chain>.json, the one address source. `--check` fails when it is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "..", "..", "app", "deployments");
const target = join(import.meta.dir, "..", "src", "deployments.generated.ts");

export function render(): string {
  const entries = readdirSync(dir).filter((f) => f.endsWith(".json") && f !== "schema.json").sort().map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")) as Record<string, any>);
  const body = entries.map((d) => JSON.stringify({ chainId: d.chainId, network: d.network, external: d.external, contracts: d.contracts, gears: (d.gears as any[]).map((g) => ({ id: g.id, symbol: g.symbol, token: g.token, poolId: g.poolId })) }, null, 2)).join(",\n");
  return `// Generated by scripts/gen-deployments.ts from app/deployments/*.json. Do not edit by hand.\n/* eslint-disable */\nexport interface DeploymentAddresses {\n  readonly chainId: number;\n  readonly network: string;\n  readonly external: Readonly<Record<string, string>>;\n  readonly contracts: Readonly<Record<string, string>>;\n  readonly gears: ReadonlyArray<{ readonly id: string; readonly symbol: string; readonly token: string; readonly poolId: string }>;\n}\n\nexport const DEPLOYMENTS: readonly DeploymentAddresses[] = [\n${body}\n];\n\nexport const deploymentFor = (chainId: number): DeploymentAddresses | undefined => DEPLOYMENTS.find((d) => d.chainId === chainId);\n`;
}

if (import.meta.main) {
  const text = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== text) { console.error("src/deployments.generated.ts is out of date: run bun run generate"); process.exit(1); }
  } else writeFileSync(target, text);
}
